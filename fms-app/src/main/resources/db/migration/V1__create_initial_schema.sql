CREATE SEQUENCE IF NOT EXISTS revinfo_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE users
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    role     VARCHAR(20)                             NOT NULL,
    email    VARCHAR(320)                            NOT NULL,
    password VARCHAR(255),
    enabled  BOOLEAN DEFAULT TRUE                    NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id)
);

CREATE TABLE departments
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name    VARCHAR(255)                            NOT NULL,
    code    VARCHAR(255)                            NOT NULL,
    user_id BIGINT                                  NOT NULL,
    CONSTRAINT pk_departments PRIMARY KEY (id)
);

CREATE TABLE department_memberships
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id       BIGINT                                  NOT NULL,
    department_id BIGINT                                  NOT NULL,
    CONSTRAINT pk_department_memberships PRIMARY KEY (id)
);

CREATE TABLE accounts
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    type          VARCHAR(30)                             NOT NULL,
    currency      VARCHAR(3)                              NOT NULL,
    department_id BIGINT                                  NOT NULL,
    CONSTRAINT pk_accounts PRIMARY KEY (id)
);

CREATE TABLE categories
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name      VARCHAR(200)                            NOT NULL,
    type      VARCHAR(20)                             NOT NULL,
    parent_id BIGINT,
    CONSTRAINT pk_categories PRIMARY KEY (id)
);

CREATE TABLE counterparties
(
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name   VARCHAR(255)                            NOT NULL,
    tax_id VARCHAR(12)                             NOT NULL,
    type   VARCHAR(20)                             NOT NULL,
    CONSTRAINT pk_counterparties PRIMARY KEY (id)
);

CREATE TABLE transactions
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    type            VARCHAR(20)                             NOT NULL,
    amount          DECIMAL(19, 4)                          NOT NULL,
    currency        VARCHAR(3)                              NOT NULL,
    date            date                                    NOT NULL,
    account_from_id BIGINT,
    account_to_id   BIGINT,
    category_id     BIGINT,
    counterparty_id BIGINT,
    reversal_of_id  BIGINT,
    status          VARCHAR(20)                             NOT NULL,
    author_id       BIGINT                                  NOT NULL,
    CONSTRAINT pk_transactions PRIMARY KEY (id)
);

CREATE TABLE budgets
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    department_id   BIGINT                                  NOT NULL,
    category_id     BIGINT                                  NOT NULL,
    amount          DECIMAL(19, 4)                          NOT NULL,
    start_of_period date                                    NOT NULL,
    end_of_period   date                                    NOT NULL,
    CONSTRAINT pk_budgets PRIMARY KEY (id)
);

CREATE TABLE audits
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    actor_id    BIGINT                                  NOT NULL,
    action      VARCHAR(20)                             NOT NULL,
    entity_type VARCHAR(20)                             NOT NULL,
    entity_id   BIGINT                                  NOT NULL,
    occurred_at TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    details     VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_audits PRIMARY KEY (id)
);

CREATE TABLE refresh_tokens
(
    jti        VARCHAR(36) NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    user_id    BIGINT      NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    revoked    BOOLEAN     NOT NULL,
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (jti)
);

CREATE TABLE revchanges
(
    rev        BIGINT NOT NULL,
    entityname VARCHAR(255)
);

CREATE TABLE revinfo
(
    rev      BIGINT NOT NULL,
    revtstmp BIGINT,
    CONSTRAINT pk_revinfo PRIMARY KEY (rev)
);

